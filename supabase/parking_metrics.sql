-- this script if the lot rows are not already in public.parking_lots.
CREATE TABLE IF NOT EXISTS public.parking_lots (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uhcl_name TEXT NOT NULL,
    unofficial_name TEXT NOT NULL,
    building TEXT NOT NULL,
    total_priority_spots INT NOT NULL CHECK (total_priority_spots >= 0),
    num_standard_spots INT NOT NULL CHECK (num_standard_spots >= 0),
    num_handicap_spots INT NOT NULL CHECK (num_handicap_spots >= 0),
    num_ev_spots INT NOT NULL CHECK (num_ev_spots >= 0)
);

