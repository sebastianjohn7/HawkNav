-- Store availability updates for individual priority spaces.
CREATE TABLE IF NOT EXISTS public.parking_spot_updates (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_lot_id INT NOT NULL REFERENCES public.parking_lots(id),
    parking_spot_id INT NOT NULL CHECK (parking_spot_id >= 1),
    parking_spot_type VARCHAR(20) NOT NULL CHECK (parking_spot_type IN ('standard', 'handicap', 'EV')),
    is_available BOOLEAN,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Validate spot indexes against the configured lot capacity.
CREATE OR REPLACE FUNCTION public.validate_parking_spot_id()
RETURNS TRIGGER AS $$
DECLARE
    max_spots INT;
BEGIN
    SELECT total_priority_spots
    INTO max_spots
    FROM public.parking_lots
    WHERE id = NEW.parking_lot_id;

    IF max_spots IS NULL THEN
        RAISE EXCEPTION 'Parking lot "%" or spot type "%" does not exist.', NEW.parking_lot_id, NEW.parking_spot_type;
    END IF;

    IF NEW.parking_spot_id > max_spots THEN
        RAISE EXCEPTION 'Invalid parking_spot_id %. For lot %, spot IDs must be between 1 and %.',
            NEW.parking_spot_id, NEW.parking_lot_id, max_spots;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 3. Attach the trigger to the updates table.
DROP TRIGGER IF EXISTS trg_validate_parking_spot_id ON public.parking_spot_updates;
CREATE TRIGGER trg_validate_parking_spot_id
BEFORE INSERT OR UPDATE ON public.parking_spot_updates
For EACH ROW
EXECUTE FUNCTION public.validate_parking_spot_id();

-- 4. Keep latest-spot lookups fast and expose read-only summary metrics.
CREATE INDEX IF NOT EXISTS idx_spot_updates_lookup 
ON public.parking_spot_updates (parking_lot_id, parking_spot_id, updated_at DESC, id DESC);

DROP VIEW IF EXISTS public.parking_lot_metrics;
CREATE VIEW public.parking_lot_metrics AS
WITH latest_spots AS (
    SELECT DISTINCT ON (parking_lot_id, parking_spot_id)
        parking_lot_id,
        parking_spot_id,
        parking_spot_type,
        is_available,
        updated_at
    FROM public.parking_spot_updates
    ORDER BY parking_lot_id, parking_spot_id, updated_at DESC, id DESC
),
spot_counts AS (
    SELECT
        parking_lot_id,
        parking_spot_type AS spot_type,
        COUNT(*) FILTER (WHERE is_available)::INT AS number_available,
        MAX(updated_at) AS latest_updated_at
    FROM latest_spots
    GROUP BY parking_lot_id, parking_spot_type
),
lot_types AS (
    SELECT
        id AS parking_lot_id,
        uhcl_name,
        unofficial_name,
        building,
        'standard'::VARCHAR(20) AS spot_type,
        num_standard_spots AS total_number
    FROM public.parking_lots
    UNION ALL
    SELECT
        id, uhcl_name, unofficial_name, building,
        'handicap'::VARCHAR(20), num_handicap_spots
    FROM public.parking_lots
    UNION ALL
    SELECT
        id, uhcl_name, unofficial_name, building,
        'EV'::VARCHAR(20), num_ev_spots
    FROM public.parking_lots
)
SELECT
    lots.parking_lot_id,
    lots.uhcl_name,
    lots.unofficial_name,
    lots.building,
    lots.spot_type,
    COALESCE(counts.number_available, 0)::INT AS number_available,
    lots.total_number,
    CASE
        WHEN lots.total_number = 0 THEN 0::NUMERIC
        ELSE ROUND(
            COALESCE(counts.number_available, 0)::NUMERIC / lots.total_number,
            4
        )
    END AS percentage,
    counts.latest_updated_at
FROM lot_types AS lots
LEFT JOIN spot_counts AS counts
    ON counts.parking_lot_id = lots.parking_lot_id
    AND counts.spot_type = lots.spot_type;

ALTER TABLE public.parking_spot_updates ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.parking_spot_updates, public.parking_lot_metrics TO anon, authenticated;

